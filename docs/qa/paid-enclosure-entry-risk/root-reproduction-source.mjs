import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {createOpeningWorld} from '../tools/check_opening.mjs';
import * as Game from '../src/simulation/game.js';
import {cameraRaidEntry} from '../src/simulation/raids.js';
import {animalSpec} from '../src/simulation/rules.js';
import {ANIMAL_ACTIONS} from '../src/simulation/animal-actions-data.js';
import {activeChunkRegion} from '../src/world/active-region.js';
import {raidEntryKey,raidEntryRequest} from '../src/world/raid-entry-data.js';
import {computeRaidEntry} from '../src/world/compute-raid-entry.js';
import {serialize} from '../src/persistence/snapshots.js';
import {numberOf} from '../src/simulation/money.js';
const {s,nav}=createOpeningWorld({seed:712,biome:'sabana',culture:'saheliana',slotId:'root-paid-enclosure-main'}),c=s.structures[0];
const bounds=[c.x+2,c.z+6.2,c.x+9,c.z+17], [x0,z0,x1,z1]=bounds;
const points=[[x0,z0],[x1,z0],[x1,z1],[x0,z1],[x0,z0]];
assert.equal(Game.plant(s,'crop','mijo',c.x+5,c.z+9,nav),true);
assert.equal(Game.previewWallChain(s,'zarzas',points,nav,{smooth:false,snap:false}).pieces.length,17);
assert.equal(Game.buildWallChain(s,'walls','zarzas',points,nav,{smooth:false,snap:false}),true);
Game.openInitialHiring(s);Game.hire(s,'hire',{olderFemale:1});assert.equal(numberOf(s.ledger.balance),495);
const radius=ANIMAL_ACTIONS.animals.warthog.presentation.footprint.radius;
const group=['warthog'],specs=[{spec:animalSpec('warthog'),radius}],before=serialize(s);
nav.setRaidView({x:c.x+5,z:c.z+9},{x:c.x+5,z:c.z+6.5});nav.setActiveBounds(activeChunkRegion(nav.raidView.eye).bounds);
const direct=cameraRaidEntry(s,specs,nav.activeBounds,nav),key=raidEntryKey(s,nav,group);
const prepared=computeRaidEntry(raidEntryRequest(s,nav,group,key,1));
assert.equal(serialize(s),before);assert.deepEqual(direct.entries,prepared.entry.entries);
assert.ok(direct.entries.every(p=>p.x>x0&&p.x<x1&&p.z>z0&&p.z<z1));
const result={scope:'Independent current-main reproduction; no raid advanced, no production mutation',bounds,radius,paidBalance:numberOf(s.ledger.balance),direct,preparedEntry:prepared.entry,snapshotUnchanged:true};
writeFileSync('.cache/root-paid-enclosure-main.json',JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
