"""Generate five small, visual-only 3D grass/brush meshes with Blender headless.

The Savanna sculpted mesh is generated by blender-grass-silhouette-variants.py.
These authored meshes use real bent ribbon geometry and vertex colour; there
are no billboards, external texture dependencies, or changes to game models.
"""
import bpy
import math
import random
from pathlib import Path

OUT=Path(__file__).resolve().parents[2]/'public/assets/visual-lab'
PRESETS={
    'grand-river': dict(seed=801,blades=19,height=(.18,.32),width=(.010,.030),lean=(.06,.19),spread=.13,
                        colors=((.17,.28,.08),(.25,.39,.11),(.36,.49,.16))),
    'mangrove': dict(seed=802,blades=16,height=(.15,.28),width=(.013,.034),lean=(.06,.17),spread=.11,
                     colors=((.13,.24,.12),(.22,.34,.16),(.33,.44,.22))),
    'volcanoes': dict(seed=803,blades=11,height=(.10,.22),width=(.010,.025),lean=(.04,.15),spread=.08,
                      colors=((.27,.22,.14),(.38,.31,.19),(.45,.38,.22))),
    'canyons': dict(seed=804,blades=13,height=(.12,.25),width=(.009,.028),lean=(.06,.18),spread=.10,
                    colors=((.35,.27,.13),(.48,.36,.19),(.58,.45,.24))),
    'desert': dict(seed=805,blades=9,height=(.08,.18),width=(.010,.024),lean=(.04,.12),spread=.07,
                  colors=((.38,.31,.18),(.51,.43,.25),(.61,.52,.33))),
}

def build(name,p):
    rng=random.Random(p['seed'])
    vertices=[]
    faces=[]
    shades=[]
    for blade in range(p['blades']):
        angle=rng.uniform(0,2*math.pi)
        heading=angle+rng.uniform(-.24,.24)
        radius=rng.uniform(.008,p['spread'])
        height=rng.uniform(*p['height'])
        width=rng.uniform(*p['width'])
        lean=rng.uniform(*p['lean'])
        base=len(vertices)
        for t in (0,.22,.47,.73,1):
            drift=radius+lean*t*t
            curve=.025*math.sin(t*math.pi)*math.sin(blade*1.63)
            dx=math.cos(heading)*drift+math.cos(heading+math.pi/2)*curve
            dy=math.sin(heading)*drift+math.sin(heading+math.pi/2)*curve
            span=width*math.sin(.16+(.84-t)*math.pi*.85)
            for sign in (-1,1):
                vertices.append((dx-sign*math.sin(angle)*span,dy+sign*math.cos(angle)*span,height*t))
        tint=p['colors'][blade%len(p['colors'])]
        for segment in range(4):
            k=base+2*segment
            faces.extend(((k,k+1,k+2),(k+1,k+3,k+2)))
            shade=.60+.11*segment
            shades.extend([tuple(min(1,value*shade) for value in tint)]*2)
    mesh=bpy.data.meshes.new(name+'-3d-ground-detail')
    mesh.from_pydata(vertices,[],faces)
    mesh.update()
    color=mesh.color_attributes.new(name='GroundDetailColor',type='BYTE_COLOR',domain='CORNER')
    for face,rgb in zip(mesh.polygons,shades):
        face.use_smooth=True
        for loop in face.loop_indices:color.data[loop].color=(*rgb,1)
    obj=bpy.data.objects.new(name+'-3d-ground-detail',mesh)
    bpy.context.collection.objects.link(obj)
    material=bpy.data.materials.new(name+'-3d-grass')
    material.use_nodes=True
    material.use_backface_culling=False
    shader=material.node_tree.nodes.get('Principled BSDF')
    shader.inputs['Roughness'].default_value=.97
    vertex=material.node_tree.nodes.new('ShaderNodeVertexColor')
    vertex.layer_name='GroundDetailColor'
    material.node_tree.links.new(vertex.outputs['Color'],shader.inputs['Base Color'])
    mesh.materials.append(material)
    return obj,len(faces)

for name,preset in PRESETS.items():
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete(use_global=False)
    obj,triangles=build(name,preset)
    bpy.ops.object.select_all(action='DESELECT')
    obj.select_set(True)
    bpy.context.view_layer.objects.active=obj
    path=OUT/(name+'-sculpted-ground-detail.glb')
    bpy.ops.export_scene.gltf(filepath=str(path),export_format='GLB',use_selection=True)
    print(name,triangles,'triangles',path.stat().st_size,'bytes')
