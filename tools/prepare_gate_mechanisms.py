"""Immutable native geometry for the existing kinematic gate assemblies."""
import hashlib
import json
import pathlib
import struct
import sys

root = pathlib.Path(__file__).resolve().parents[1]
pack_path = root / 'public/content/walls.json'
pack = json.loads(pack_path.read_text(encoding='utf-8'))
calibration_path = root / 'content/manifests/gate-leaf-calibration.json'
leaves = json.loads(calibration_path.read_text(encoding='utf-8'))['leaves']
body_height = json.loads((root / 'content/manifests/gate-frames-native.json').read_text(encoding='utf-8'))['bodyHeight']
def text_hash(path):
    return hashlib.sha256(path.read_bytes().replace(b'\r\n', b'\n')).hexdigest()

sources = {calibration_path.relative_to(root).as_posix(): text_hash(calibration_path)}
for dependency in (pack_path, root / 'content/manifests/gate-frames-native.json'):
    sources[dependency.relative_to(root).as_posix()] = text_hash(dependency)

def load(descriptor, code):
    path = root / 'public' / descriptor['url'].lstrip('/')
    data = path.read_bytes()
    sources[path.relative_to(root).as_posix()] = hashlib.sha256(data).hexdigest()
    return struct.unpack('<' + code * (len(data) // struct.calcsize(code)), data)

def clip(poly, axis, bound, sign):
    out = []
    for i, a in enumerate(poly):
        b = poly[(i + 1) % len(poly)]
        da, db = (a[axis] - bound) * sign, (b[axis] - bound) * sign
        if da >= 0:
            out.append(a)
        if (da >= 0) != (db >= 0):
            t = da / (da - db)
            out.append(tuple(a[k] + (b[k] - a[k]) * t for k in range(3)))
    return out

def partition(poly, leaf):
    frame = []
    for axis, bound, sign in ((0, leaf['left'], 1), (0, leaf['right'], -1), (1, leaf['top'], -1)):
        outside = clip(poly, axis, bound, -sign)
        if len(outside) >= 3:
            frame.append(outside)
        poly = clip(poly, axis, bound, sign)
        if len(poly) < 3:
            break
    return frame, poly if len(poly) >= 3 else []

def hull(points):
    points = sorted(set(points))
    def cross(a, b, c):
        return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
    halves = []
    for sequence in (points, reversed(points)):
        part = []
        for p in sequence:
            while len(part) > 1 and cross(part[-2], part[-1], p) <= 0:
                part.pop()
            part.append(p)
        halves.append(part[:-1])
    return halves[0] + halves[1]

def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]

def literal(value):
    text = format(f32(value), '.9g')
    return text + ('' if '.' in text or 'e' in text else '.0') + 'f'

lines = ['// Generated by tools/prepare_gate_mechanisms.py. Do not edit.', '#pragma once',
         'struct NativeGateMeshModel {int id,vertices,policyCount;double hx,hz,height;const float* positions;const unsigned char* leaf;const double* policy;};']
models, records = [], []
for model_id, material in enumerate(('zarzas', 'empalizada', 'reforzado'), 1):
    piece, leaf = pack['pieces'][material + '_puerta'], leaves[material]
    positions, indices = load(piece['p'], 'f'), load(piece['i'], 'H')
    points = [positions[i:i+3] for i in range(0, len(positions), 3)]
    out, flags, projected = [], [], []
    scale = 1.6 if material == 'reforzado' else 1
    for at in range(0, len(indices), 3):
        frame, moving = partition([points[j] for j in indices[at:at+3]], leaf)
        projected.extend((p[0], p[2]) for p in clip(moving, 1, body_height / scale, -1))
        for polygon, moving_flag in [*( (p, 0) for p in frame), (moving, 1)]:
            for i in range(1, len(polygon)-1):
                for vertex in (polygon[0], polygon[i], polygon[i+1]):
                    out.extend(f32(v) for v in vertex)
                    flags.append(moving_flag)
    policy = [v for p in hull(projected) for v in p]
    lines += [f'inline constexpr float gateMesh{model_id}Positions[]={{' + ','.join(literal(v) for v in out) + '};',
              f'inline constexpr unsigned char gateMesh{model_id}Leaf[]={{' + ','.join(map(str, flags)) + '};',
              f'inline constexpr double gateMesh{model_id}Policy[]={{' + ','.join(repr(v) for v in policy) + '};']
    models.append('{' + f'{model_id},{len(flags)},{len(policy)//2},{leaf["hinge"][0]!r},{leaf["hinge"][1]!r},{body_height!r},gateMesh{model_id}Positions,gateMesh{model_id}Leaf,gateMesh{model_id}Policy' + '}')
    records.append({'id': model_id, 'material': material, 'vertices': len(flags), 'leafVertices': sum(flags), 'frameVertices': len(flags)-sum(flags)})
lines += ['inline constexpr NativeGateMeshModel gateMeshModels[]={' + ','.join(models) + '};',
          'inline const NativeGateMeshModel* nativeGateMeshModel(int id){return id>=1&&id<=3?&gateMeshModels[id-1]:nullptr;}']
target = root / 'src/world/wild-engine/spatial-gate-mechanisms-native.h'
data = ('\n'.join(lines) + '\n').encode('utf-8')
manifest = {'version': 1, 'model': 'kinematic-union', 'sourceHashPolicy': 'JSON normalized to LF; binary assets exact', 'scope': 'Canonical frame/leaf triangle union; no internal occupied region is removed. Same cut and rigid hinge as rendering. Native support is validated separately.',
            'sources': sources, 'models': records, 'headerSha256': hashlib.sha256(data).hexdigest()}
manifest_path = root / 'content/manifests/gate-mechanisms-native.json'
manifest_data = (json.dumps(manifest, indent=2)+'\n').encode('utf-8')
if '--check' in sys.argv:
    if not target.exists() or target.read_bytes() != data or not manifest_path.exists() or manifest_path.read_bytes() != manifest_data:
        raise SystemExit('Native gate mechanisms are stale; run tools/prepare_gate_mechanisms.py')
else:
    target.write_bytes(data)
    manifest_path.write_bytes(manifest_data)
