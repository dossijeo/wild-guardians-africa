// Recover resource initialization, never an obsolete world's drawing or GPU
// simulation. The producer must record fresh passes for the admitted world.
export function rejectedFramePreparations(operations, validTexturePreparation) {
  const retained=[];
  for(const op of operations){
    if(['writeBuffer','writeTexture','copyExternalImageToTexture'].includes(op.method)){retained.push(op);continue;}
    if(op.method!=='submit')return null;
    const buffers=[];
    for(const buffer of op.args[0]){
      if(buffer.texturePreparation){if(!validTexturePreparation(buffer))return null;buffers.push(buffer);continue;}
      // Render passes are regenerated by the owner. Compute/readback/copies may
      // have one-shot state that cannot be inferred from a rejected frame.
      if(buffer.__remoteCommands.some(command=>!['beginRenderPass','insertDebugMarker','pushDebugGroup','popDebugGroup'].includes(command.method)))return null;
    }
    if(buffers.length)retained.push({method:'submit',args:[buffers]});
  }
  return retained;
}

export function closePreparationImages(operations) {
  const closed=new Set();
  for(const op of operations)if(op.method==='copyExternalImageToTexture'){
    const source=op.args[0]?.source;
    if(source&&!closed.has(source)){closed.add(source);source.close?.();}
  }
}
