function sampleChunk(positions,cx,cz,x,z,tolerance=0){
  if(!positions?.length)return undefined;
  let localX=x-(cx*48-24),localZ=z-(cz*48-24);
  if(localX< -tolerance||localX>48+tolerance||localZ< -tolerance||localZ>48+tolerance)return undefined;
  localX=Math.max(0,Math.min(48,localX));localZ=Math.max(0,Math.min(48,localZ));
  const ix=Math.min(47,Math.floor(localX)),iz=Math.min(47,Math.floor(localZ)),fx=localX-ix,fz=localZ-iz;
  const at=(gx,gz)=>positions[(gz*49+gx)*3+1];
  if(fx+fz<=1){const a=at(ix,iz);return a+(at(ix+1,iz)-a)*fx+(at(ix,iz+1)-a)*fz;}
  const c=at(ix+1,iz+1);return c+(at(ix,iz+1)-c)*(1-fx)+(at(ix+1,iz)-c)*(1-fz);
}

// Read-only surface sampling from chunks generated by the spatial WASM core.
// The view retains worker-transferred render buffers; it does not regenerate
// relief or maintain a second procedural terrain recipe.
export class SpatialSurfaceView {
  constructor(){this.chunks=new Map();}
  install(payload){
    if(!Number.isSafeInteger(payload?.cx)||!Number.isSafeInteger(payload?.cz)||
       !(payload.terrain?.positions instanceof Float32Array)||
       payload.terrain.positions.length!==49*49*3)
      throw new TypeError('Invalid spatial terrain payload');
    this.chunks.set(`${payload.cx},${payload.cz}`,payload.terrain.positions);
  }
  remove(cx,cz){return this.chunks.delete(`${cx},${cz}`);}
  clear(){this.chunks.clear();}
  get size(){return this.chunks.size;}
  surfaceInChunk(cx,cz,x,z){if(!Number.isSafeInteger(cx)||!Number.isSafeInteger(cz)||!Number.isFinite(x)||!Number.isFinite(z))return undefined;return sampleChunk(this.chunks.get(`${cx},${cz}`),cx,cz,x,z,1e-8);}
  surface(x,z){
    if(!Number.isFinite(x)||!Number.isFinite(z))return undefined;
    const cx=Math.floor((x+24)/48),cz=Math.floor((z+24)/48);
    const onLeft=x===cx*48-24,onTop=z===cz*48-24;
    for(const px of onLeft?[cx,cx-1]:[cx])for(const pz of onTop?[cz,cz-1]:[cz]){
      const value=sampleChunk(this.chunks.get(`${px},${pz}`),px,pz,x,z);if(value!==undefined)return value;
    }
    return undefined;
  }
}
